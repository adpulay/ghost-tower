#!/usr/bin/env node
// eval/run_eval: score every scenario against simulator ground truth (A.md Phase 6).
//
//   npm run eval                      everything (3 runs/scenario + ablation + load), writes eval/results.md
//   npm run eval -- --only main       just the scenario table
//   npm run eval -- --only ablation   just the fusion ablation (TESTING.md §2c)
//   npm run eval -- --only load       just the recluster load test (300 / 1,000 / 3,000 phones)
//   npm run eval -- --runs 5 demo-01  pick runs and scenarios; --no-write to only print
//
// Runs use the real module in-process (spacetime/test/harness.ts), driven on sim time, so
// numbers are reproducible and need no server. Run i uses seed "<seed>" (i=1) or "<seed>/r<i>".
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { ABLATION_PRESETS, type FusionWeights } from '../../spacetime/src/fusion.ts';
import { listScenarios, loadScenario } from '../../sim/src/scenario.ts';
import { runLocal } from './local_run.ts';
import { quantile, score, type Metrics } from './metrics.ts';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'results.md');

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    runs: { type: 'string', default: '3' },
    only: { type: 'string' },
    'no-write': { type: 'boolean', default: false },
  },
});
const RUNS = parseInt(values.runs!, 10);
const scenarios = positionals.length ? positionals : listScenarios();
const want = (part: string) => !values.only || values.only === part;

const seedSuffix = (i: number) => (i === 0 ? '' : `/r${i + 1}`);
const f = (x: number | null | undefined, d = 0) => (x === null || x === undefined || Number.isNaN(x) ? 'n/a' : x.toFixed(d));
const median = (xs: (number | null)[]) => quantile(xs.filter((x): x is number => x !== null), 0.5);

async function runMany(id: string, weights?: FusionWeights, runs = RUNS): Promise<Metrics[]> {
  const s = loadScenario(id);
  const out: Metrics[] = [];
  for (let i = 0; i < runs; i++) out.push(score(await runLocal(s, { seedSuffix: seedSuffix(i), weights, mockAlerts: true })));
  return out;
}

const md: string[] = [
  '# Ghost Tower: eval results',
  '',
  `Generated by \`npm run eval\` (eval/src/run_eval.ts). In-process module on sim time; ${RUNS} seeded runs per scenario, medians shown.`,
  'Regenerate after any change to `spacetime/src/tracking.ts`, `fusion.ts` or the scenarios.',
  '',
];

if (want('main')) {
  console.log(`scenarios x ${RUNS} runs...`);
  const rows: string[] = [];
  let benignActive = 0, benignPhoneHours = 0;
  for (const id of scenarios) {
    const s = loadScenario(id);
    const ms = await runMany(id);
    const g = (k: keyof Metrics) => median(ms.map(m => m[k] as number | null));
    if (s.kind === 'benign') {
      benignActive += ms.reduce((a, m) => a + m.activeTracks, 0);
      benignPhoneHours += (s.phones * (s.duration_s ?? 600) * RUNS) / 3600;
    }
    const row = [
      id, s.kind, f(g('timeToFirstAlertS')), f(g('timeToUsableFixS')), f(g('errMedianM')), f(g('errP90M')),
      f(g('protectedPct')), `${ms.map(m => m.activeTracks).join('/')}`, f(g('falseActiveTracks')),
      f(g('eventPrecision'), 2), f(g('eventRecall'), 2), f(g('reclusterMeanMs'), 1),
    ];
    rows.push(`| ${row.join(' | ')} |`);
    console.log(row.join('  '));
  }
  md.push(
    '## Scenarios (TESTING.md §1, §3)',
    '',
    '| Scenario | Kind | First alert (s) | Usable fix (s) | Err median (m) | Err p90 (m) | Protected before hit (%) | Active tracks per run | False active | Event precision | Event recall | recluster mean (ms) |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
    `**False alarms (benign scenarios): ${benignActive} active tracks in ${benignPhoneHours.toFixed(0)} phone-hours = ` +
      `${f((benignActive / benignPhoneHours) * 1000, 2)} per 1,000 phone-hours.**`,
    '',
    'How to read it:',
    '- *First alert*: first `active` track on the blaster minus its first on-air second. Reports reach Spacetime only after the phone leaves the 2G cell (5-10 s) plus 1-4 s upload, so this cannot be ~0.',
    '- *Usable fix*: first time the error is ≤ 300 m and stays there for 30 s.',
    '- *Error*: per recluster pass (every 3 s) while on air, distance from the associated active track to the true position.',
    '- *Protected before hit*: **uses a stand-in for the agent alerts** (every 30 s per active track, a corridor 600 m either side of a straight 5-min projection). The real number depends on Role 2\'s agent + `predict_route`; re-measure once it runs.',
    '- *Event precision/recall*: an event counts as "predicted" if it ended up on a track that went active; ground truth is whether a blaster caused it.',
    '',
  );
}

if (want('ablation')) {
  console.log('fusion ablation...');
  const sets: [string, string][] = [
    ['text_only', 'Text only'], ['drop_only', '2G drop only'], ['text_drop', 'Text + 2G drop'], ['all_three', 'All three (+ carrier log check)'],
  ];
  const abl = ['demo-01', 'twin-01', 'benign-01', 'benign-02', 'border-01'];
  const rows: string[] = [];
  for (const [key, label] of sets) {
    const w = ABLATION_PRESETS[key];
    let falseActive = 0, tp = 0, fp = 0, pos = 0;
    for (const id of abl) {
      for (const m of await runMany(id, w)) {
        falseActive += m.falseActiveTracks;
        tp += m.eventCounts.tp;
        fp += m.eventCounts.fp;
        pos += m.eventCounts.pos;
      }
    }
    const row = [label, f(tp + fp ? tp / (tp + fp) : null, 2), f(pos ? tp / pos : null, 2), String(falseActive)];
    rows.push(`| ${row.join(' | ')} |`);
    console.log(row.join('  '));
  }
  md.push(
    '## Fusion ablation (TESTING.md §2c)',
    '',
    `Weights from \`ABLATION_PRESETS\` (spacetime/src/fusion.ts), subsets renormalized to sum to 1; the +0.1 SMSC confidence bonus is only on with the carrier signal. ` +
      `Scenarios: ${abl.join(', ')}; ${RUNS} runs each. Precision/recall pool every event of every run; false active tracks are summed over all runs.`,
    '',
    '| Signals | Event precision | Event recall | False active tracks |',
    '|---|---|---|---|',
    ...rows,
    '',
    'Caveat: benign real-toll texts use a cached classifier score of 0.55-0.95 (an assumption that real TxTag reminders look scammy to a text model). Set `CLASSIFIER_URL` and re-run with Role 2\'s real scores.',
    '',
  );
}

if (want('load')) {
  console.log('load test...');
  const rows: string[] = [];
  for (const phones of [300, 1000, 3000]) {
    const r = await runLocal(loadScenario('demo-01'), { phones });
    const ms = r.reclusterMs;
    const row = [phones.toLocaleString('en-US'), String(r.events.length), f(quantile(ms, 0.5), 1), f(quantile(ms, 0.95), 1), f(Math.max(...ms), 1)];
    rows.push(`| ${row.join(' | ')} |`);
    console.log(row.join('  '));
  }
  md.push(
    '## Load test (TESTING.md §2a)',
    '',
    'demo-01 with more phones in the same area (so density, hits per pass and events in the window all grow). Timing is one `recluster` pass in the **local wasm test datastore under Node**, not Maincloud; use it for relative scaling and re-measure on the shared instance.',
    '',
    '| Phones | Events in run | recluster p50 (ms) | p95 (ms) | max (ms) |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  );
}

if (!values['no-write'] && !values.only && !positionals.length) {
  writeFileSync(OUT, md.join('\n'));
  console.log(`wrote ${OUT}`);
} else if (!values['no-write']) {
  console.log('(partial run: results.md not overwritten; run `npm run eval` with no args to regenerate it)');
}
